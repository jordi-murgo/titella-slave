def _require_windows():
    """The device layer only exists on Windows; say so with a coded error.

    Without this the first ctypes call would raise AttributeError inside the
    stream worker and kill the thread, hiding the real cause from the caller.
    """
    if _kernel32 is None or _hid is None or _setupapi is None:
        raise HidStreamError(
            "hid_unsupported",
            "the HID transport is only available on Windows",
        )


def _is_invalid(handle):
    return handle is None or handle == 0 or handle == INVALID_HANDLE_VALUE


def _error_message(prefix, code):
    try:
        text = ctypes.FormatError(code).strip()
    except (AttributeError, ValueError):  # pragma: no cover - non-Windows
        text = ""
    return "%s failed with %d%s" % (prefix, code, (": " + text) if text else "")


class _Interface(object):
    def __init__(self, path, probe):
        self.path = path
        self.probe = probe


def _interface_path(set_handle, data):
    required = wintypes.DWORD(0)
    _setupapi.SetupDiGetDeviceInterfaceDetailW(
        set_handle, ctypes.byref(data), None, 0, ctypes.byref(required), None)
    if not required.value:
        return None
    buffer = ctypes.create_string_buffer(required.value)
    # cbSize is 6 on x86 and 8 on x64, but the device path always starts at
    # offset 4 on both: reading it at offset 8 drops two UTF-16 characters.
    ctypes.memmove(buffer, ctypes.byref(wintypes.DWORD(8 if ctypes.sizeof(
        ctypes.c_void_p) == 8 else 6)), 4)
    if not _setupapi.SetupDiGetDeviceInterfaceDetailW(
            set_handle, ctypes.byref(data), buffer, required.value,
            ctypes.byref(required), None):
        return None
    return ctypes.wstring_at(ctypes.addressof(buffer) + 4)


def _serial_number(handle):
    buffer = ctypes.create_unicode_buffer(128)
    if not _hid.HidD_GetSerialNumberString(
            handle, buffer, ctypes.sizeof(buffer)):
        return None
    return buffer.value or None


def _probe(path, serial):
    """Same classification as ``HidDeviceBrowser.Probe``."""
    handle = _kernel32.CreateFileW(
        path, 0, FILE_SHARE_READ | FILE_SHARE_WRITE, None, OPEN_EXISTING, 0, None)
    if _is_invalid(handle):
        return _PROBE_DENIED
    try:
        attributes = HIDD_ATTRIBUTES()
        attributes.Size = ctypes.sizeof(HIDD_ATTRIBUTES)
        if not _hid.HidD_GetAttributes(handle, ctypes.byref(attributes)):
            return _PROBE_DENIED
        if attributes.VendorID != VENDOR_ID or attributes.ProductID != PRODUCT_ID:
            return _PROBE_OTHER
        device_serial = _serial_number(handle)
        if device_serial is None or device_serial != serial:
            return _PROBE_OTHER
        preparsed = ctypes.c_void_p()
        if not _hid.HidD_GetPreparsedData(handle, ctypes.byref(preparsed)):
            return _PROBE_INCOMPATIBLE
        try:
            caps = HIDP_CAPS()
            if _hid.HidP_GetCaps(preparsed, ctypes.byref(caps)) != HIDP_STATUS_SUCCESS:
                return _PROBE_INCOMPATIBLE
            if caps.UsagePage != USAGE_PAGE_VENDOR or caps.Usage != USAGE_DATA:
                return _PROBE_OTHER
            if (caps.InputReportByteLength != COLLECTION_REPORT_BYTES
                    or caps.OutputReportByteLength != COLLECTION_REPORT_BYTES
                    or caps.FeatureReportByteLength != COLLECTION_REPORT_BYTES):
                return _PROBE_INCOMPATIBLE
            return _PROBE_EXACT
        finally:
            _hid.HidD_FreePreparsedData(preparsed)
    finally:
        _kernel32.CloseHandle(handle)


def _path_carries_identity(path):
    if not path:
        return False
    lowered = path.lower()
    return "vid_17ef" in lowered and "pid_a38f" in lowered


def find_data_collection(serial):
    """Returns the device interface path of the one matching collection."""
    _require_windows()
    class_guid = GUID()
    _hid.HidD_GetHidGuid(ctypes.byref(class_guid))
    set_handle = _setupapi.SetupDiGetClassDevsW(
        ctypes.byref(class_guid), None, None, DIGCF_PRESENT | DIGCF_DEVICEINTERFACE)
    if _is_invalid(set_handle):
        raise HidStreamError(
            "hid_not_found",
            _error_message("SetupDiGetClassDevsW", ctypes.get_last_error()))
    exact = 0
    incompatible = 0
    denied = 0
    exact_path = None
    try:
        data = SP_DEVICE_INTERFACE_DATA()
        data.cbSize = ctypes.sizeof(SP_DEVICE_INTERFACE_DATA)
        index = 0
        while True:
            if not _setupapi.SetupDiEnumDeviceInterfaces(
                    set_handle, None, ctypes.byref(class_guid), index,
                    ctypes.byref(data)):
                error = ctypes.get_last_error()
                if error == ERROR_NO_MORE_ITEMS:
                    break
                raise HidStreamError(
                    "hid_not_found",
                    _error_message("SetupDiEnumDeviceInterfaces", error))
            index += 1
            path = _interface_path(set_handle, data)
            if path is None:
                continue
            probe = _probe(path, serial)
            if probe == _PROBE_EXACT:
                exact += 1
                exact_path = path
            elif probe == _PROBE_INCOMPATIBLE:
                incompatible += 1
            elif probe == _PROBE_DENIED and _path_carries_identity(path):
                denied += 1
    finally:
        _setupapi.SetupDiDestroyDeviceInfoList(set_handle)
    if exact == 1:
        return exact_path
    if exact > 1:
        raise HidStreamError(
            "hid_ambiguous", "several HID data collections match the device serial")
    if incompatible > 0:
        raise HidStreamError(
            "hid_incompatible",
            "the HID data collection does not expose 64-byte IN/OUT/Feature reports")
    if denied > 0:
        raise HidStreamError(
            "hid_access_denied", "the HID data collection could not be inspected")
    raise HidStreamError(
        "hid_not_found", "no HID data collection for serial %s is present" % serial)


class Win32HidReportIo(ReportIo):
    """Overlapped 64-byte report I/O on the vendor collection."""

    def __init__(self, serial):
        self._serial = serial
        self._write_gate = threading.Lock()
        self._read_buffer = ctypes.create_string_buffer(REPORT_BYTES)
        self._write_buffer = ctypes.create_string_buffer(REPORT_BYTES)
        self._overlapped_read = OVERLAPPED()
        self._overlapped_write = OVERLAPPED()
        self._handle = None
        self._read_event = None
        self._write_event = None
        self._read_pending = False
        self._write_pending = False
        self._opened = False
        self._disposed = False
        self._mutex = None

    # ── device ──────────────────────────────────────────────────────────
    def _ensure_open(self):
        if self._opened:
            return
        _require_windows()
        self._acquire_mutex()
        path = find_data_collection(self._serial)
        handle = _kernel32.CreateFileW(
            path, GENERIC_READ | GENERIC_WRITE, FILE_SHARE_READ | FILE_SHARE_WRITE,
            None, OPEN_EXISTING, FILE_FLAG_OVERLAPPED, None)
        if _is_invalid(handle):
            raise HidStreamError(
                "hid_access_denied",
                _error_message("CreateFileW on the HID collection",
                               ctypes.get_last_error()))
        read_event = _kernel32.CreateEventW(None, True, False, None)
        write_event = _kernel32.CreateEventW(None, True, False, None)
        if _is_invalid(read_event) or _is_invalid(write_event):
            error = ctypes.get_last_error()
            for event in (read_event, write_event):
                if not _is_invalid(event):
                    _kernel32.CloseHandle(event)
            _kernel32.CloseHandle(handle)
            raise HidStreamError(
                "hid_io_error", _error_message("CreateEventW", error))
        self._overlapped_read.hEvent = read_event
        self._overlapped_write.hEvent = write_event
        self._handle = handle
        self._read_event = read_event
        self._write_event = write_event
        self._opened = True

    def _acquire_mutex(self):
        name = "Local\\Titella.Hid." + self._serial
        mutex = _kernel32.CreateMutexW(None, False, name)
        if _is_invalid(mutex):
            raise HidStreamError(
                "hid_busy", _error_message("CreateMutexW", ctypes.get_last_error()))
        wait = _kernel32.WaitForSingleObject(mutex, 0)
        if wait not in (WAIT_OBJECT_0, 0x00000080):  # WAIT_OBJECT_0, WAIT_ABANDONED
            _kernel32.CloseHandle(mutex)
            raise HidStreamError(
                "hid_busy",
                "another Titella consumer holds Local\\Titella.Hid." + self._serial)
        self._mutex = mutex

    # ── reads ───────────────────────────────────────────────────────────
    def read(self, report, timeout_ms):
        if self._disposed:
            return -1
        self._ensure_open()
        if not self._read_pending:
            transferred = wintypes.DWORD(0)
            started = _kernel32.ReadFile(
                self._handle, ctypes.byref(self._read_buffer), REPORT_BYTES,
                ctypes.byref(transferred), ctypes.byref(self._overlapped_read))
            if started:
                return _copy_read(self._read_buffer, report, transferred.value)
            error = ctypes.get_last_error()
            if error != ERROR_IO_PENDING:
                raise HidStreamError(
                    "hid_io_error",
                    _error_message("ReadFile on the HID collection", error))
            self._read_pending = True
        wait = _kernel32.WaitForSingleObject(self._read_event, max(int(timeout_ms), 0))
        if wait != WAIT_OBJECT_0:
            return 0
        self._read_pending = False
        _kernel32.ResetEvent(self._read_event)
        transferred = wintypes.DWORD(0)
        if not _kernel32.GetOverlappedResult(
                self._handle, ctypes.byref(self._overlapped_read),
                ctypes.byref(transferred), False):
            error = ctypes.get_last_error()
            if error == ERROR_OPERATION_ABORTED:
                return -1
            raise HidStreamError(
                "hid_io_error",
                _error_message("GetOverlappedResult after a HID read", error))
        return _copy_read(self._read_buffer, report, transferred.value)

    # ── writes ──────────────────────────────────────────────────────────
    def write(self, report):
        if self._disposed:
            raise HidStreamError("hid_closed", "the HID stream was disposed")
        self._ensure_open()
        with self._write_gate:
            if self._write_pending and not self._write_completed():
                raise HidStreamError(
                    "hid_write_timeout", "a previous HID write is still pending")
            if len(report) < REPORT_BYTES:
                raise HidStreamError(
                    "hid_io_error", "a 64-byte report is required")
            ctypes.memmove(self._write_buffer, bytes(report[:REPORT_BYTES]),
                           REPORT_BYTES)
            transferred = wintypes.DWORD(0)
            started = _kernel32.WriteFile(
                self._handle, ctypes.byref(self._write_buffer), REPORT_BYTES,
                ctypes.byref(transferred), ctypes.byref(self._overlapped_write))
            if not started:
                pending = ctypes.get_last_error()
                if pending != ERROR_IO_PENDING:
                    raise HidStreamError(
                        "hid_io_error",
                        _error_message("WriteFile on the HID collection", pending))
                self._write_pending = True
                wait = _kernel32.WaitForSingleObject(
                    self._write_event, WRITE_TIMEOUT_MS)
                if wait != WAIT_OBJECT_0:
                    _kernel32.CancelIoEx(
                        self._handle, ctypes.byref(self._overlapped_write))
                    raise HidStreamError(
                        "hid_write_timeout",
                        "the HID write did not complete within %d ms"
                        % WRITE_TIMEOUT_MS)
                self._write_pending = False
                _kernel32.ResetEvent(self._write_event)
            written = wintypes.DWORD(0)
            if not _kernel32.GetOverlappedResult(
                    self._handle, ctypes.byref(self._overlapped_write),
                    ctypes.byref(written), False):
                error = ctypes.get_last_error()
                if error == ERROR_OPERATION_ABORTED:
                    raise HidStreamError("hid_closed", "the HID write was cancelled")
                raise HidStreamError(
                    "hid_io_error",
                    _error_message("GetOverlappedResult after a HID write", error))
            if written.value != REPORT_BYTES:
                raise HidStreamError(
                    "hid_io_error",
                    "short HID write: %d of %d bytes" % (written.value, REPORT_BYTES))

    def _write_completed(self):
        if not self._write_pending:
            return True
        if not self._handle:
            return False
        wait = _kernel32.WaitForSingleObject(self._write_event, 0)
        if wait != WAIT_OBJECT_0:
            return False
        transferred = wintypes.DWORD(0)
        _kernel32.GetOverlappedResult(
            self._handle, ctypes.byref(self._overlapped_write),
            ctypes.byref(transferred), False)
        self._write_pending = False
        _kernel32.ResetEvent(self._write_event)
        return True

    # ── teardown ────────────────────────────────────────────────────────
    def close(self):
        """Cancels any operation still owned by the kernel, then releases."""
        if self._disposed:
            return
        self._disposed = True
        if self._handle:
            for pending, overlapped, event in (
                    (self._read_pending, self._overlapped_read, self._read_event),
                    (self._write_pending, self._overlapped_write, self._write_event)):
                if not pending:
                    continue
                _kernel32.CancelIoEx(self._handle, ctypes.byref(overlapped))
                if not _is_invalid(event):
                    _kernel32.WaitForSingleObject(event, CANCEL_SETTLE_MS)
            self._read_pending = False
            self._write_pending = False
            for event in (self._read_event, self._write_event):
                if not _is_invalid(event):
                    _kernel32.CloseHandle(event)
            self._read_event = None
            self._write_event = None
            _kernel32.CloseHandle(self._handle)
            self._handle = None
        if self._mutex:
            _kernel32.ReleaseMutex(self._mutex)
            _kernel32.CloseHandle(self._mutex)
            self._mutex = None
        self._opened = False


def _copy_read(source, report, transferred):
    """Copies a completed read into ``report`` and zero-fills the rest."""
    if transferred == 0:
        return 0
    take = min(transferred, REPORT_BYTES)
    report[0:take] = ctypes.string_at(ctypes.addressof(source), take)
    for index in range(take, REPORT_BYTES):
        report[index] = 0
    return take


def open_stream(binding, clock=None):
    """Opens the HID data collection named by ``HID:<serial>``.

    Single entry point of the packaged transport: the loader types the
    binding, the agent opens the stream, and neither has to know that the
    device side is a separate layer internally. The binding is validated and
    the platform checked before a worker thread exists, so a caller on the
    wrong OS gets one clear error instead of a dead thread.
    """
    serial = parse_binding(binding)
    _require_windows()
    return HidByteStream.open(
        binding, lambda name: Win32HidReportIo(name), clock=clock)
