"""HID data transport: the Python endpoint of the firmware's report 0x10 flow.

This is a line-by-line port of the reference implementation in
``implementations/windows/HidByteStream.cs``; that C# unit stays the
normative description of the protocol and of every state transition. Both
peers must agree frame by frame, so the port keeps the same field names, the
same order of checks and the same retry semantics rather than a "cleaner"
reformulation.

Report 0x10 (64 bytes including the report ID, little-endian):
  [0]      report ID 0x10
  [1]      protocol version (1)
  [2]      class: OPEN=1 OPEN_ACK=2 DATA=3 ACK=4 CLOSE=5
  [3..6]   epoch, uint32, non-zero, generated by whoever opens
  [7..8]   sequence, uint16, per direction
  [9]      length 0..54 (zero for OPEN/OPEN_ACK/ACK/CLOSE, 1..54 for DATA)
  [10..63] payload; zero padding outside the length

One DATA frame is in flight per direction; exact duplicates are
re-acknowledged without being re-applied; controls (OPEN_ACK, ACK, CLOSE)
overtake data; a send that goes unanswered for 250 ms is retransmitted up to
three times before the link fails explicitly. This module never touches the
0x11 loader mailbox.

Two halves live here because the packaged artifact is exactly one transport
unit, mirroring the single C# source: the state machine (``HidByteStream``),
which is platform independent and testable against a fake peer, and the Win32
device side (``Win32HidReportIo`` / ``find_data_collection``) that finds the
vendor collection by VID/PID *and* USB serial, verifies the 64-byte report
shape and drives overlapping I/O. The named mutex
``Local\\Titella.Hid.<serial>`` serialises access; Windows mutexes are
thread-affine, so it is taken and released only on the thread doing the I/O.

Stdlib only, ctypes only: a bare Windows host has no third-party package.
"""

from __future__ import print_function

import ctypes
import os
import threading
import time
from ctypes import wintypes

REPORT_ID = 0x10
REPORT_BYTES = 64
PROTOCOL_VERSION = 1
QUEUE_BYTES = 8192
DATA_MAX = 54
RETRY_TIMEOUT_MS = 250
MAX_RETRIES = 3

POLL_MS = 5
READ_IDLE_MS = 100
OPEN_BUDGET_MS = 1000
DISPOSE_JOIN_MS = 1000

BINDING_PREFIX = "HID:"
SERIAL_CHARS = 12

CLASS_OPEN = 1
CLASS_OPEN_ACK = 2
CLASS_DATA = 3
CLASS_ACK = 4
CLASS_CLOSE = 5

STATE_DISCONNECTED = 0
STATE_OPENING = 1
STATE_CONNECTED = 2

_BINDING_HEX = frozenset("0123456789ABCDEF")


class HidStreamError(IOError):
    """Stream failure carrying the same ``titella_code`` the C# peer sets."""

    def __init__(self, code, message):
        IOError.__init__(self, message)
        self.code = code
        self.message = message


def is_hid_binding(value):
    """True for the exact ``HID:<12 uppercase hex>`` form."""
    if not isinstance(value, str):
        return False
    if len(value) != len(BINDING_PREFIX) + SERIAL_CHARS:
        return False
    if not value.startswith(BINDING_PREFIX):
        return False
    return all(char in _BINDING_HEX for char in value[len(BINDING_PREFIX):])


def parse_binding(binding):
    if not is_hid_binding(binding):
        raise HidStreamError(
            "invalid_argument",
            "the HID binding must be HID:<12 uppercase hexadecimal characters>",
        )
    return binding[len(BINDING_PREFIX):]


def _now_ms():
    return int(time.monotonic() * 1000.0)


def _u32(value):
    return value & 0xFFFFFFFF


def _u16(value):
    return value & 0xFFFF


def build_report(frame_class, epoch, sequence, data=None):
    """One canonical 0x10 report, exactly like ``BuildReportLocked``."""
    report = bytearray(REPORT_BYTES)
    report[0] = REPORT_ID
    report[1] = PROTOCOL_VERSION
    report[2] = frame_class
    report[3:7] = _u32(epoch).to_bytes(4, "little")
    report[7:9] = _u16(sequence).to_bytes(2, "little")
    if data:
        take = min(len(data), DATA_MAX)
        report[9] = take
        report[10:10 + take] = data[:take]
    return bytes(report)


def parse_report(report):
    """Returns ``(class, epoch, sequence, payload)`` or ``None`` when invalid."""
    if report is None or len(report) < REPORT_BYTES:
        return None
    if report[0] != REPORT_ID or report[1] != PROTOCOL_VERSION:
        return None
    epoch = int.from_bytes(report[3:7], "little")
    if epoch == 0:
        return None
    frame_class = report[2]
    if frame_class < CLASS_OPEN or frame_class > CLASS_CLOSE:
        return None
    length = report[9]
    if frame_class == CLASS_DATA:
        if length == 0 or length > DATA_MAX:
            return None
    elif length != 0:
        return None
    sequence = int.from_bytes(report[7:9], "little")
    return frame_class, epoch, sequence, bytes(report[10:10 + length])


class ReportIo(object):
    """The device side the stream drives; kept tiny so a fake peer is trivial.

    ``read`` returns the number of bytes of a complete report placed in
    ``report``, ``0`` when the timeout expired and ``-1`` when the device is
    gone. ``write`` blocks until the report was handed to the device.
    """

    def read(self, report, timeout_ms):
        raise NotImplementedError

    def write(self, report):
        raise NotImplementedError

    def close(self):
        raise NotImplementedError


class HidByteStream(object):
    """Reliable byte stream over the 0x10 report flow.

    Both roles live in one state machine, exactly as in the firmware endpoint:
    an *active* stream opens with its own non-zero epoch and retries OPEN until
    the peer answers, while a *passive* one starts disconnected and adopts the
    epoch of the first OPEN it receives. The host side of the rig is the active
    role; the passive role exists for the peer of a crossed test and for any
    future device-side user of this module.
    """

    def __init__(self, io, epoch, clock=None, active=True):
        if io is None:
            raise ValueError("a report IO is required")
        epoch = _u32(int(epoch))
        if active and epoch == 0:
            raise ValueError("a non-zero epoch is required")
        if not active and epoch != 0:
            raise ValueError("a passive stream adopts the peer's epoch")
        self._io = io
        self._clock = clock or _now_ms
        self._gate = threading.Condition(threading.RLock())
        self._in_report = bytearray(REPORT_BYTES)
        self._out_report = bytearray(REPORT_BYTES)
        self._tx_queue = bytearray(QUEUE_BYTES)
        self._rx_queue = bytearray(QUEUE_BYTES)
        self._tx_head = 0
        self._tx_length = 0
        self._rx_head = 0
        self._rx_length = 0
        self._state = STATE_OPENING if active else STATE_DISCONNECTED
        self._epoch = epoch
        self._tx_sequence = 0
        self._rx_sequence = 0
        self._pending_valid = False
        self._pending_sequence = 0
        self._pending_length = 0
        self._pending_attempt = 0
        self._pending_deadline = 0
        self._flight_data = b""
        self._scratch_data = b""
        self._ack_pending = False
        self._ack_sequence = 0
        self._open_ack_pending = False
        self._close_pending = False
        self._close_epoch = 0
        self._open_sent = False
        self._open_attempt = 0
        self._open_deadline = 0
        self._last_rx_valid = False
        self._last_rx_sequence = 0
        self._last_rx_length = 0
        self._last_rx_data = b""
        self._staged = None
        self._staged_take = 0
        self._tx_enqueued = 0
        self._tx_acknowledged = 0
        self._generation = 0
        self._cancelled = False
        self._dispose_requested = False
        self._disposed = False
        self._failure_code = None
        self._failure_message = None
        self._worker = threading.Thread(target=self._worker_loop, name="titella-hid")
        self._worker.daemon = True
        self._worker.start()

    # ── lifecycle ───────────────────────────────────────────────────────
    @classmethod
    def open(cls, binding, io_factory, clock=None):
        """Opens the collection of ``binding`` and completes the OPEN handshake."""
        serial = parse_binding(binding)
        stream = cls(io_factory(serial), _next_epoch(), clock=clock)
        stream.wait_for_open(OPEN_BUDGET_MS)
        return stream

    def wait_for_open(self, budget_ms):
        started = _now_ms()
        failure = None
        with self._gate:
            while True:
                if self._state == STATE_CONNECTED:
                    return
                if self._failure_code is not None:
                    failure = self._build_failure_locked()
                    break
                remaining = budget_ms - (_now_ms() - started)
                if remaining <= 0:
                    break
                self._gate.wait(min(remaining, 50) / 1000.0)
        used = _now_ms() - started
        self._shutdown(max(0, budget_ms - used))
        if failure is not None:
            raise failure
        raise HidStreamError(
            "hid_open_timeout",
            "the HID OPEN handshake did not complete within %d ms" % OPEN_BUDGET_MS,
        )

    def _shutdown(self, join_budget_ms):
        with self._gate:
            first = not self._disposed
            self._disposed = True
            if self._state != STATE_CONNECTED:
                self._cancelled = True
            self._gate.notify_all()
        if first and join_budget_ms > 0 and self._worker is not threading.current_thread():
            self._worker.join(join_budget_ms / 1000.0)

    def close(self):
        first = False
        with self._gate:
            if not self._disposed:
                self._disposed = True
                first = True
            if self._state == STATE_CONNECTED:
                self._dispose_requested = True
                self._close_epoch = self._epoch
                self._reset_flow_keep_close()
            else:
                self._cancelled = True
            self._gate.notify_all()
        if first and self._worker is not threading.current_thread():
            self._worker.join(DISPOSE_JOIN_MS / 1000.0)

    # ── stream interface ────────────────────────────────────────────────
    def read(self, count):
        """Up to ``count`` bytes; ``b""`` after 100 ms without data."""
        if count <= 0:
            return b""
        started = _now_ms()
        with self._gate:
            while True:
                self._throw_if_unavailable_locked()
                if self._rx_length > 0:
                    take = min(count, self._rx_length)
                    data = self._pop_ring(self._rx_queue, "rx", take)
                    return data
                remaining = READ_IDLE_MS - (_now_ms() - started)
                if remaining <= 0:
                    return b""
                self._gate.wait(min(remaining, READ_IDLE_MS) / 1000.0)

    def write(self, data):
        """Queues ``data`` and returns once the peer acknowledged those bytes."""
        if not data:
            return
        with self._gate:
            self._throw_if_unavailable_locked()
            generation = self._generation
            watermark = self._tx_enqueued + len(data)
            written = 0
            while written < len(data):
                self._throw_if_unavailable_locked()
                self._throw_if_generation_locked(generation)
                free = QUEUE_BYTES - self._tx_length
                if free > 0:
                    take = min(free, len(data) - written)
                    self._push_ring(self._tx_queue, "tx", data[written:written + take])
                    self._tx_enqueued += take
                    written += take
                    self._gate.notify_all()
                if written < len(data):
                    self._gate.wait(0.1)
            while True:
                self._throw_if_unavailable_locked()
                self._throw_if_generation_locked(generation)
                if self._tx_acknowledged >= watermark:
                    return
                self._gate.wait(0.1)

    def flush(self):
        with self._gate:
            self._throw_if_unavailable_locked()
            generation = self._generation
            while (self._tx_length > 0 or self._pending_valid or self._ack_pending
                   or self._open_ack_pending or self._close_pending
                   or self._state == STATE_OPENING):
                self._throw_if_unavailable_locked()
                self._throw_if_generation_locked(generation)
                self._gate.wait(0.1)

    # ── worker ──────────────────────────────────────────────────────────
    def _worker_loop(self):
        try:
            while True:
                with self._gate:
                    stop = self._cancelled or self._failure_code is not None
                    finishing = self._dispose_requested and not self._close_pending
                if stop or finishing:
                    break
                if not self._pump_outbound():
                    with self._gate:
                        stop = (self._cancelled or self._failure_code is not None
                                or (self._dispose_requested and not self._close_pending))
                    if stop:
                        break
                    try:
                        read = self._io.read(self._in_report, POLL_MS)
                    except (IOError, OSError) as error:
                        self._fail_locked(self._coded(error))
                        break
                    except BaseException as error:  # never let the worker die silently
                        self._fail_locked(HidStreamError(
                            "hid_io_error", "%s: %s" % (type(error).__name__, error)))
                        break
                    if read < 0:
                        break
                    if read > 0:
                        if read != REPORT_BYTES:
                            # A short report must never reach the parser: the
                            # reused buffer can still carry a valid header.
                            self._in_report = bytearray(REPORT_BYTES)
                            continue
                        with self._gate:
                            self._handle_inbound_locked(bytes(self._in_report))
                        continue
        except BaseException as error:  # pragma: no cover - defensive
            self._fail_locked(HidStreamError(
                "hid_io_error", "%s: %s" % (type(error).__name__, error)))
        finally:
            self._finish_worker()

    def _pump_outbound(self):
        sent_any = False
        while True:
            with self._gate:
                if self._cancelled or self._failure_code is not None:
                    return sent_any
                staged = self._fill_next_report_locked()
            if staged is None:
                return sent_any
            try:
                self._io.write(staged)
            except (IOError, OSError) as error:
                self._fail_locked(self._coded(error))
                return sent_any
            except BaseException as error:  # never let the worker die silently
                self._fail_locked(HidStreamError(
                    "hid_io_error", "%s: %s" % (type(error).__name__, error)))
                return sent_any
            sent_any = True
            with self._gate:
                self._confirm_send_locked()
                self._gate.notify_all()

    def _fill_next_report_locked(self):
        self._staged = None
        now = self._clock()
        if self._close_pending:
            self._staged = (CLASS_CLOSE, build_report(CLASS_CLOSE, self._close_epoch, 0))
            return self._staged[1]
        if self._state == STATE_OPENING:
            if not self._open_sent:
                self._staged = (CLASS_OPEN, build_report(CLASS_OPEN, self._epoch, 0))
                return self._staged[1]
            if _elapsed(now, self._open_deadline) < 0:
                return None
            if self._open_attempt > MAX_RETRIES:
                self._fail_locked(HidStreamError(
                    "hid_retry_exhausted",
                    "the peer never answered the HID OPEN",
                ))
                return None
            self._staged = (CLASS_OPEN, build_report(CLASS_OPEN, self._epoch, 0))
            return self._staged[1]
        if self._state != STATE_CONNECTED:
            return None
        if self._open_ack_pending:
            self._staged = (CLASS_OPEN_ACK,
                            build_report(CLASS_OPEN_ACK, self._epoch, 0))
            return self._staged[1]
        if self._ack_pending:
            self._staged = (CLASS_ACK,
                            build_report(CLASS_ACK, self._epoch, self._ack_sequence))
            return self._staged[1]
        if self._pending_valid:
            if _elapsed(now, self._pending_deadline) < 0:
                return None
            if self._pending_attempt > MAX_RETRIES:
                self._fail_locked(HidStreamError(
                    "hid_retry_exhausted",
                    "the peer never acknowledged the in-flight HID DATA",
                ))
                return None
            self._staged = (CLASS_DATA, build_report(
                CLASS_DATA, self._epoch, self._pending_sequence, self._flight_data))
            return self._staged[1]
        if self._tx_length > 0:
            take = min(self._tx_length, DATA_MAX)
            peeked = self._peek_ring(self._tx_queue, "tx", take)
            self._scratch_data = peeked
            self._staged_take = take
            self._staged = (CLASS_DATA, build_report(
                CLASS_DATA, self._epoch, self._tx_sequence, peeked))
            return self._staged[1]
        return None

    def _confirm_send_locked(self):
        staged, self._staged = self._staged, None
        now = self._clock()
        if staged is None:
            return
        kind = staged[0]
        if kind == CLASS_OPEN:
            self._open_sent = True
            self._open_attempt += 1
            self._open_deadline = _u32(now + RETRY_TIMEOUT_MS)
        elif kind == CLASS_OPEN_ACK:
            self._open_ack_pending = False
        elif kind == CLASS_ACK:
            self._ack_pending = False
        elif kind == CLASS_CLOSE:
            self._close_pending = False
        elif kind == CLASS_DATA:
            if self._pending_valid:
                self._pending_attempt += 1
            else:
                self._pop_ring(self._tx_queue, "tx", self._staged_take)
                self._pending_length = self._staged_take
                self._pending_sequence = self._tx_sequence
                self._tx_sequence = _u16(self._tx_sequence + 1)
                self._flight_data = self._scratch_data
                self._pending_valid = True
                self._pending_attempt = 1
            self._pending_deadline = _u32(now + RETRY_TIMEOUT_MS)

    def _handle_inbound_locked(self, report):
        parsed = parse_report(report)
        if parsed is None:
            return
        frame_class, epoch, sequence, payload = parsed
        if frame_class == CLASS_OPEN:
            if self._state == STATE_CONNECTED and epoch == self._epoch:
                self._open_ack_pending = True
                self._gate.notify_all()
                return
            self._reset_flow_locked()
            self._epoch = epoch
            self._state = STATE_CONNECTED
            self._open_ack_pending = True
        elif frame_class == CLASS_OPEN_ACK:
            if self._state == STATE_OPENING and epoch == self._epoch:
                self._state = STATE_CONNECTED
                self._open_sent = False
                self._open_attempt = 0
                self._open_deadline = 0
        elif frame_class == CLASS_DATA:
            if self._state != STATE_CONNECTED or epoch != self._epoch:
                self._gate.notify_all()
                return
            if sequence == self._rx_sequence:
                if len(payload) > QUEUE_BYTES - self._rx_length:
                    # Backpressure: never copy partially and never acknowledge
                    # bytes that were not admitted; the retransmission returns.
                    self._gate.notify_all()
                    return
                self._push_ring(self._rx_queue, "rx", payload)
                self._last_rx_valid = True
                self._last_rx_sequence = sequence
                self._last_rx_length = len(payload)
                self._last_rx_data = payload
                self._rx_sequence = _u16(sequence + 1)
                self._ack_pending = True
                self._ack_sequence = sequence
            elif (self._last_rx_valid and sequence == self._last_rx_sequence
                  and len(payload) == self._last_rx_length
                  and payload == self._last_rx_data):
                self._ack_pending = True
                self._ack_sequence = sequence
        elif frame_class == CLASS_ACK:
            if (self._state == STATE_CONNECTED and epoch == self._epoch
                    and self._pending_valid and sequence == self._pending_sequence):
                self._pending_valid = False
                self._tx_acknowledged += self._pending_length
                self._pending_length = 0
        elif frame_class == CLASS_CLOSE:
            if self._state != STATE_DISCONNECTED and epoch == self._epoch:
                self._fail_locked(HidStreamError(
                    "hid_peer_closed", "the peer closed the HID session"))
        self._gate.notify_all()

    def _reset_flow_keep_close(self):
        closing_epoch = self._close_epoch
        self._reset_flow_locked()
        self._close_epoch = closing_epoch
        self._close_pending = True
        self._state = STATE_DISCONNECTED
        self._epoch = 0

    def _reset_flow_locked(self):
        self._tx_head = 0
        self._tx_length = 0
        self._rx_head = 0
        self._rx_length = 0
        self._tx_sequence = 0
        self._rx_sequence = 0
        self._pending_valid = False
        self._pending_length = 0
        self._pending_attempt = 0
        self._pending_deadline = 0
        self._ack_pending = False
        self._ack_sequence = 0
        self._open_ack_pending = False
        self._close_pending = False
        self._close_epoch = 0
        self._open_sent = False
        self._open_attempt = 0
        self._open_deadline = 0
        self._last_rx_valid = False
        self._last_rx_length = 0
        self._staged = None
        self._tx_acknowledged = self._tx_enqueued
        self._generation += 1

    def _fail_locked(self, error):
        with self._gate:
            if self._failure_code is None:
                self._failure_code = getattr(error, "code", None) or "hid_io_error"
                self._failure_message = str(error)
            self._reset_flow_locked()
            self._state = STATE_DISCONNECTED
            self._epoch = 0
            self._gate.notify_all()

    def _finish_worker(self):
        with self._gate:
            self._cancelled = True
            if self._failure_code is None and not self._disposed:
                self._failure_code = "hid_io_error"
                self._failure_message = "the HID worker stopped"
            self._reset_flow_locked()
            self._state = STATE_DISCONNECTED
            self._epoch = 0
            self._gate.notify_all()
        try:
            self._io.close()
        except (IOError, OSError):
            pass

    def _throw_if_unavailable_locked(self):
        if self._disposed:
            raise HidStreamError("hid_closed", "the HID stream was disposed")
        if self._failure_code is not None:
            raise self._build_failure_locked()

    def _throw_if_generation_locked(self, generation):
        if self._generation != generation:
            raise HidStreamError(
                "hid_session_reset",
                "a new HID session began; unacknowledged bytes were discarded",
            )

    def _build_failure_locked(self):
        return HidStreamError(self._failure_code, self._failure_message)

    @staticmethod
    def _coded(error):
        code = getattr(error, "code", None)
        if code:
            return error
        return HidStreamError(getattr(error, "titella_code", None) or "hid_io_error",
                              str(error))

    # ── ring helpers ────────────────────────────────────────────────────
    def _push_ring(self, ring, which, data):
        head = self._tx_head if which == "tx" else self._rx_head
        length = self._tx_length if which == "tx" else self._rx_length
        for index, byte in enumerate(data):
            ring[(head + length + index) % QUEUE_BYTES] = byte
        if which == "tx":
            self._tx_length = length + len(data)
        else:
            self._rx_length = length + len(data)

    def _pop_ring(self, ring, which, count):
        head = self._tx_head if which == "tx" else self._rx_head
        length = self._tx_length if which == "tx" else self._rx_length
        take = min(count, length)
        out = bytearray(take)
        for index in range(take):
            out[index] = ring[(head + index) % QUEUE_BYTES]
        if which == "tx":
            self._tx_head = (head + take) % QUEUE_BYTES
            self._tx_length = length - take
        else:
            self._rx_head = (head + take) % QUEUE_BYTES
            self._rx_length = length - take
        return bytes(out)

    def _peek_ring(self, ring, which, count):
        head = self._tx_head if which == "tx" else self._rx_head
        length = self._tx_length if which == "tx" else self._rx_length
        take = min(count, length)
        out = bytearray(take)
        for index in range(take):
            out[index] = ring[(head + index) % QUEUE_BYTES]
        return bytes(out)


def _elapsed(now, deadline):
    """Signed difference in the wrapped 32-bit millisecond domain."""
    diff = _u32(now - deadline)
    return diff - 0x100000000 if diff >= 0x80000000 else diff


_epoch_counter = [0]
_epoch_lock = threading.Lock()


def _next_epoch():
    import os
    with _epoch_lock:
        _epoch_counter[0] += 1
        counter = _epoch_counter[0]
    mixed = _u32(counter * 2654435761)
    clock = _u32(int(time.monotonic() * 1000.0) ^ int(os.getpid() << 16))
    epoch = mixed ^ clock
    return epoch or 0xA5A50001


